#!/usr/bin/env node
// Copies CHANGELOG.md into a module the server bundles, so `/changelog`
// shows the notes of the build it runs and reads no file at request time.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(appRoot, 'CHANGELOG.md')
const md = existsSync(source) ? readFileSync(source, 'utf8') : ''

const target = resolve(appRoot, 'server/changelog.generated.ts')
const next = `// AUTO-GENERATED by scripts/write-changelog.mjs from CHANGELOG.md — do not edit.
export const CHANGELOG_MD = ${JSON.stringify(md)}
`

const prev = existsSync(target) ? readFileSync(target, 'utf8') : null
if (prev !== next) writeFileSync(target, next)
